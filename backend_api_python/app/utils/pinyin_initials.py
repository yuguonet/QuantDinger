def pinyin_initials(text: str) -> str:
    """
    Convert Chinese text to pinyin initials.

    Args:
        text: Chinese text, e.g. "贵州茅台"

    Returns:
        Pinyin initials string, e.g. "gzmt"
        Non-Chinese characters are kept as-is (lowercased).
    """
    result = []
    for ch in text:
        if ch in _MAP:
            result.append(_MAP[ch])
        elif '\u4e00' <= ch <= '\u9fff':
            # Unmapped Chinese char — skip (can't determine initial)
            continue
        elif ch.isascii() and ch.isalpha():
            result.append(ch.lower())
        elif ch.isdigit():
            result.append(ch)
    return ''.join(result)
