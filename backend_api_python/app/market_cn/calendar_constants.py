def holiday_group(missing_workdays: int) -> str:
    """按「相邻两交易日之间缺失的工作日数」给假期分组。

    用实际休市断点而非名义节日日期 => 清明/调休/节日落周末自动对齐。

    :param missing_workdays: 相邻两个交易日之间缺失的工作日数(>=1 才算假期)
    :return: "short"(1-2日) / "mid"(3-4日) / "long"(>=5日, 即春节+国庆)
    """
    if missing_workdays <= 2:
        return "short"
    if missing_workdays <= 4:
        return "mid"
    return "long"


def window_key(a: int, b: int) -> str:
    """组合窗口的字典键: window_key(-3, 1) == "-3->1" """
    return f"{a}->{b}"


